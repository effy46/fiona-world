import {chromium} from 'playwright';
import {mkdir,writeFile} from 'node:fs/promises';
const out='output/playwright/notebook-entry';await mkdir(out,{recursive:true});
const browser=await chromium.launch({channel:'chrome'});
const page=await browser.newPage({viewport:{width:1600,height:1100}});
const errors=[];const checks=[];
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
const url='http://127.0.0.1:5201/?v=entry-smoke';
try{
  await page.goto(url,{waitUntil:'domcontentloaded'});
  await page.locator('[data-loaded="true"]').waitFor({timeout:45000});
  const clasp=page.getByRole('button',{name:'Open notebook',exact:true});
  await clasp.waitFor();await page.waitForTimeout(1800);
  if(await page.locator('main').getAttribute('data-opening')!=='closed')throw Error('Book did not start closed.');
  if(await page.getByRole('button',{name:'Read the pages',exact:true}).isVisible())throw Error('Book controls exposed while closed.');
  await page.screenshot({path:`${out}/01-closed.png`});checks.push('closed cover and clasp before interaction');
  await clasp.focus();await page.keyboard.press('Enter');
  await page.locator('[data-opening="opening"]').waitFor();
  await page.waitForTimeout(280);await page.screenshot({path:`${out}/02-unlatching.png`});
  await page.waitForTimeout(950);await page.screenshot({path:`${out}/03-opening.png`});
  await page.locator('[data-ready="true"]').waitFor({timeout:15000});
  await page.locator('[data-cat-phase="idle"]').waitFor({timeout:7000});
  await page.screenshot({path:`${out}/04-open.png`});checks.push('clasp, cover, popup and entry cat complete');
  await page.getByRole('button',{name:'Explore the paper world',exact:false}).click();await page.waitForTimeout(2400);
  await page.screenshot({path:`${out}/05-smoke.png`});await page.screenshot({path:`${out}/smoke-detail.png`,clip:{x:575,y:505,width:220,height:365}});await page.waitForTimeout(850);await page.screenshot({path:`${out}/06-smoke-later.png`});
  checks.push('camp smoke visual captures');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'Making',exact:true}).click();
  await page.locator('[data-spread="making"][data-turning="false"]').waitFor({timeout:10000});
  await page.screenshot({path:`${out}/07-making.png`});
  await page.getByRole('button',{name:'Turn back',exact:true}).click();await page.locator('[data-spread="start"][data-turning="false"]').waitFor({timeout:10000});
  checks.push('forward and backward chapters after cover opening');
  await page.emulateMedia({reducedMotion:'reduce'});await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('[data-loaded="true"]').waitFor({timeout:45000});await clasp.click();
  await page.locator('[data-ready="true"]').waitFor({timeout:4000});await page.screenshot({path:`${out}/08-reduced.png`});checks.push('reduced motion skips entry movement');
  await page.emulateMedia({reducedMotion:'no-preference'});await page.setViewportSize({width:390,height:844});await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('[data-loaded="true"]').waitFor({timeout:45000});await page.waitForTimeout(1800);await page.screenshot({path:`${out}/09-mobile-closed.png`});
  await clasp.click();await page.locator('[data-ready="true"]').waitFor({timeout:15000});await page.locator('[data-cat-phase="idle"]').waitFor({timeout:7000});
  await page.screenshot({path:`${out}/10-mobile-open.png`});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');checks.push('mobile closed clasp and open framing');
}catch(e){errors.push(e.message);await page.screenshot({path:`${out}/failure.png`});}
await browser.close();await writeFile(`${out}/verification.json`,JSON.stringify({checks,errors},null,2)+'\n');console.log(JSON.stringify({checks,errors}));if(errors.length)process.exitCode=1;
